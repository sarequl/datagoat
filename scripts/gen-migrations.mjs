#!/usr/bin/env node
// Bundles migrations/*.sql into src/db/migrations.generated.ts so the Worker can apply pending
// migrations itself (src/db/migrate.ts), however the deploy command is configured.
//   node scripts/gen-migrations.mjs          write the file
//   node scripts/gen-migrations.mjs --check  fail if the committed file is stale (npm run check)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "migrations");
const out = join(root, "src", "db", "migrations.generated.ts");

// Same discovery and order as wrangler: top-level *.sql files sorted by name.
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();
const entries = files.map(
  (name) =>
    `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(readFileSync(join(dir, name), "utf8"))} },`,
);
const content = `// GENERATED by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit.
// Run \`npm run gen:migrations\` after adding a migration (npm run build does it too).
import type { BundledMigration } from "./migrate";

export const MIGRATIONS: readonly BundledMigration[] = [
${entries.join("\n")}
];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== content) {
    console.error(
      "src/db/migrations.generated.ts is stale: run `npm run gen:migrations` and commit it.",
    );
    process.exit(1);
  }
  console.log(`migrations bundle is current (${files.length} file(s))`);
} else {
  writeFileSync(out, content);
  console.log(`wrote src/db/migrations.generated.ts (${files.length} migration(s))`);
}
